def load_artifacts():
    """Load only the trusted model generated by this project's notebook."""
    if not MODEL_PATH.exists() or not METADATA_PATH.exists():
        raise RuntimeError("Model files are missing. Run notebooks/Complete_ML_Workflow.ipynb first.")
    model = joblib.load(MODEL_PATH)
    metadata = json.loads(METADATA_PATH.read_text(encoding="utf-8"))
    expected = metadata["feature_names"]
    if expected != [field["name"] for field in FIELDS]:
        raise RuntimeError("Form fields do not match the exported model metadata.")
    if list(model.feature_names_in_) != expected:
        raise RuntimeError("Exported pipeline feature names do not match metadata.")
    return model, metadata


def validate_input(form, metadata):
    """Return an ordered DataFrame row, display values, and field errors."""
    values, display_values, errors = {}, {}, {}
    for field in FIELDS:
        name = field["name"]
        raw = (form.get(name) or "").strip()
        if not raw:
            errors[name] = "This field is required."
            continue
        if "options" in field:
            choices = dict(field["options"])
            if raw not in choices or int(raw) not in metadata["categorical_values"][name]:
                errors[name] = "Choose a valid option."
                continue
            values[name] = int(raw)
            display_values[name] = choices[raw]
        else:
            try:
                number = float(raw)
            except ValueError:
                errors[name] = "Enter a valid number."
                continue
            if not math.isfinite(number):
                errors[name] = "Enter a finite number."
                continue
            limits = metadata["numeric_ranges"][name]
            if not limits["min"] <= number <= limits["max"]:
                errors[name] = f"Enter a value from {limits['min']:g} to {limits['max']:g}."
                continue
            if name != "oldpeak" and not number.is_integer():
                errors[name] = "Enter a whole number."
                continue
            values[name] = number
            display_values[name] = raw
    if errors:
        return None, display_values, errors
    row = pd.DataFrame([values], columns=metadata["feature_names"])
    return row, display_values, errors


def create_app():
    app = Flask(__name__)
    model, metadata = load_artifacts()
    app.config["MODEL"] = model
    app.config["MODEL_METADATA"] = metadata

    @app.get("/")
    def index():
        return render_template("index.html", fields=FIELDS, metadata=metadata, values={}, errors={})

    @app.post("/predict")
    def predict():
        row, display_values, errors = validate_input(request.form, metadata)
        if errors:
            return render_template("index.html", fields=FIELDS, metadata=metadata,
                                   values=request.form, errors=errors), 400
        try:
            prediction = int(model.predict(row)[0])
            if prediction not in (0, 1):
                raise ValueError("Model returned an unexpected class.")
            probability = None
            if hasattr(model, "predict_proba"):
                classes = list(model.classes_)
                probability = float(model.predict_proba(row)[0][classes.index(prediction)])
        except (ValueError, TypeError, KeyError, IndexError):
            app.logger.exception("Prediction failed")
            return render_template("index.html", fields=FIELDS, metadata=metadata,
                                   values=request.form,
                                   errors={"form": "Prediction could not be completed. Please review your entries."}), 400
        return render_template("result.html", prediction=prediction,
                               result=("Heart disease present" if prediction else "No heart disease predicted"),
                               probability=probability, model_name=metadata["selected_model_name"],
                               fields=FIELDS, display_values=display_values)

    @app.get("/about")
    def about():
        return render_template("about.html", metadata=metadata)

    return app


if __name__ == "__main__":
    create_app().run(debug=False)
